#!/usr/bin/env bun
/**
 * 把 Nitro 的 bun 产物 + 内嵌静态资源编译成单文件可执行程序。
 *
 * 前置：先执行 bun run build（vite build + tsc），产出 .output/。
 * 输出：.output/server-bin（Windows 下为 .output/server-bin.exe）
 *
 * 资源内嵌方式：
 *   - 生成 .assets.generated.ts，用 with { type: "file" } 引入 public 下每个文件；
 *   - 用 --asset-naming="[dir]/[name].[ext]" 保留相对路径，便于 Nitro 的
 *     readAsset 在运行时按 <root>/.output/public/... 读取。
 */
import { Glob } from "bun"
import { existsSync } from "node:fs"
import path from "node:path"

const ROOT = path.resolve(import.meta.dir, "..")
process.chdir(ROOT)

const OUTPUT_DIR = path.join(ROOT, ".output")
const PUBLIC_DIR = path.join(OUTPUT_DIR, "public")
const SERVER_ENTRY = path.join(OUTPUT_DIR, "server", "index.mjs")
const GENERATED = path.join(ROOT, ".assets.generated.ts")
const OUTFILE = path.join(OUTPUT_DIR, process.platform === "win32" ? "server-bin.exe" : "server-bin")

function fail(message) {
  console.error("[build-binary] " + message)
  process.exit(1)
}

if (!existsSync(SERVER_ENTRY)) {
  fail("未找到 .output/server/index.mjs，请先运行 bun run build")
}
if (!existsSync(PUBLIC_DIR)) {
  fail("未找到 .output/public，请检查构建产物")
}

// ── 收集 public 下的所有文件 ────────────────────────
const files = []
for await (const relative of new Glob("**/*").scan({ cwd: PUBLIC_DIR, onlyFiles: true })) {
  files.push(relative.split(path.sep).join("/"))
}
files.sort()

if (files.length === 0) {
  fail(".output/public 为空，无法内嵌静态资源")
}

// ── 生成资源清单（URL 路径 -> 内嵌文件路径） ────────
const source = ["// AUTO-GENERATED by scripts/build-binary.mjs — do not edit.", ""]
const entries = []
files.forEach((relative, index) => {
  source.push(`import a${index} from "./.output/public/${relative}" with { type: "file" }`)
  entries.push(`  "/${relative}": a${index},`)
})
source.push("")
source.push("export const assetPaths: Record<string, string> = {")
source.push(...entries)
source.push("}")
source.push(`export const assetCount = ${files.length}`)
source.push("")

await Bun.write(GENERATED, source.join("\n"))
console.log(`[build-binary] 内嵌 ${files.length} 个静态资源 -> .assets.generated.ts`)

// ── 编译单文件可执行程序 ────────────────────────────
const result = Bun.spawnSync(
  [
    "bun",
    "build",
    "--compile",
    "--target=bun",
    "--asset-naming=[dir]/[name].[ext]",
    "server-prod.ts",
    "--outfile",
    OUTFILE,
  ],
  { stdio: ["inherit", "inherit", "inherit"], cwd: ROOT },
)

if (result.exitCode !== 0) {
  fail("bun build --compile 失败（exit " + result.exitCode + "）")
}

const sizeMb = (Bun.file(OUTFILE).size / 1024 / 1024).toFixed(1)
console.log(`[build-binary] 完成：${path.relative(ROOT, OUTFILE)} (${sizeMb} MB)`)
